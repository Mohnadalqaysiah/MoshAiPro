import re

_DIACRITICS = re.compile(r"[ً-ْـ]")   # تشكيل + تطويل


def _normalize(text: str) -> str:
    """
    توحيد الكتابة العربية قبل المطابقة.

    (2026-09-17) بلا هذا فشل «ليش ما وصلتني اشارات» رغم وجود «ما وصلني»
    بالكلمات المفتاحية. وملاحقة الصيغ بإضافة مرادفات لا تنتهي: جمهورنا
    يكتب بلهجات مختلفة، وبهمزات وتاء مربوطة وألف مقصورة متفاوتة. توحيد
    الحرف مرة واحدة يغطي ما لا تغطيه قوائم المرادفات مهما طالت.
    """
    t = (text or "").strip().lower()
    t = _DIACRITICS.sub("", t)
    t = t.replace("أ", "ا").replace("إ", "ا").replace("آ", "ا")
    t = t.replace("ة", "ه").replace("ى", "ي")
    t = t.replace("ؤ", "و").replace("ئ", "ي")
    return re.sub(r"\s+", " ", t)


def answer(message: str) -> str:
    """
    يُعيد جواباً عن المنصة، أو "" إن لم يكن السؤال عنها.

    الترتيب مقصود: الأسئلة المحدّدة قبل العامة. سؤال «لماذا لا تصلني
    إشارات رغم اشتراكي» يحوي «اشتراك» — ولو فُحصت الأسعار أولاً لأجبناه
    بجدول باقات وهو مشترك أصلاً، وذلك أسوأ من الصمت.
    """
    msg = _normalize(message)
    if not msg:
        return ""
    for key, words in _KEYWORDS:
        if any(_normalize(w) in msg for w in words):
            return _plans_answer() if key == "plans" else _ANSWERS.get(key, "")
    return ""
